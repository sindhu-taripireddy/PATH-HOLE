import os
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, Image as RLImage
from app.config import settings

def generate_pdf_report(detection, output_filepath: str):
    """
    Generates a PDF inspection report for a pothole detection record.
    """
    doc = SimpleDocTemplate(
        output_filepath,
        pagesize=letter,
        rightMargin=36, leftMargin=36, topMargin=36, bottomMargin=36
    )
    styles = getSampleStyleSheet()
    story = []

    # Title Banner
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontSize=24,
        textColor=colors.HexColor('#0F172A'),
        spaceAfter=6,
        fontName='Helvetica-Bold'
    )
    subtitle_style = ParagraphStyle(
        'DocSubTitle',
        parent=styles['Normal'],
        fontSize=11,
        textColor=colors.HexColor('#64748B'),
        spaceAfter=20
    )

    story.append(Paragraph("POTHOLEGUARD INSPECTION REPORT", title_style))
    story.append(Paragraph("AI-Based Real-Time Pothole Detection, Severity Analysis & Geolocation System", subtitle_style))
    story.append(Spacer(1, 10))

    # Metadata Table
    meta_data = [
        [Paragraph("<b>Detection ID:</b>", styles['Normal']), Paragraph(f"#{detection.id}", styles['Normal']),
         Paragraph("<b>Date & Time:</b>", styles['Normal']), Paragraph(f"{detection.created_at.strftime('%Y-%m-%d %H:%M:%S')}", styles['Normal'])],
        [Paragraph("<b>Source Type:</b>", styles['Normal']), Paragraph(f"{detection.source_type.upper()}", styles['Normal']),
         Paragraph("<b>Location:</b>", styles['Normal']), Paragraph(f"{detection.location_name or 'GPS Captured'}", styles['Normal'])],
        [Paragraph("<b>GPS Coordinates:</b>", styles['Normal']), Paragraph(f"{detection.latitude or 'N/A'}, {detection.longitude or 'N/A'}", styles['Normal']),
         Paragraph("<b>Potholes Found:</b>", styles['Normal']), Paragraph(f"{detection.pothole_count}", styles['Normal'])],
        [Paragraph("<b>Avg Confidence:</b>", styles['Normal']), Paragraph(f"{detection.avg_confidence}%", styles['Normal']),
         Paragraph("<b>Est. Size Area:</b>", styles['Normal']), Paragraph(f"{detection.total_estimated_area_cm2} cm²", styles['Normal'])],
    ]

    meta_table = Table(meta_data, colWidths=[110, 150, 110, 150])
    meta_table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,-1), colors.HexColor('#F8FAFC')),
        ('BOX', (0,0), (-1,-1), 1, colors.HexColor('#CBD5E1')),
        ('INNERGRID', (0,0), (-1,-1), 0.5, colors.HexColor('#E2E8F0')),
        ('PADDING', (0,0), (-1,-1), 8),
    ]))
    story.append(meta_table)
    story.append(Spacer(1, 20))

    # Severity Breakdown Header
    story.append(Paragraph("<b>Severity Breakdown & Hazard Analysis</b>", styles['Heading2']))
    story.append(Spacer(1, 8))

    sev_data = [
        ["High Severity (Hazardous)", "Medium Severity (Caution)", "Low Severity (Minor)", "Overall Assessment"],
        [f"{detection.high_severity_count}", f"{detection.medium_severity_count}", f"{detection.low_severity_count}",
         "URGENT REPAIR NEEDED" if detection.high_severity_count > 0 else "SCHEDULED MAINTENANCE"]
    ]
    sev_table = Table(sev_data, colWidths=[130, 130, 130, 150])
    sev_table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,0), colors.HexColor('#1E293B')),
        ('TEXTCOLOR', (0,0), (-1,0), colors.white),
        ('ALIGN', (0,0), (-1,-1), 'CENTER'),
        ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
        ('BOTTOMPADDING', (0,0), (-1,0), 6),
        ('BACKGROUND', (0,1), (-1,1), colors.HexColor('#F1F5F9')),
        ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor('#CBD5E1')),
        ('PADDING', (0,0), (-1,-1), 8),
    ]))
    story.append(sev_table)
    story.append(Spacer(1, 20))

    # Image Evidence
    story.append(Paragraph("<b>Computer Vision AI Detection Evidence</b>", styles['Heading2']))
    story.append(Spacer(1, 8))

    if os.path.exists(detection.processed_filepath):
        try:
            img = RLImage(detection.processed_filepath, width=520, height=300)
            story.append(img)
        except Exception as e:
            story.append(Paragraph(f"Image evidence file path: {detection.processed_filepath}", styles['Normal']))
    else:
        story.append(Paragraph("Processed detection image evidence attached to record.", styles['Normal']))

    story.append(Spacer(1, 20))
    story.append(Paragraph("Report Generated by PotholeGuard Infrastructure Monitoring AI.", ParagraphStyle('Footer', parent=styles['Italic'], textColor=colors.HexColor('#94A3B8'))))

    doc.build(story)
    return output_filepath
